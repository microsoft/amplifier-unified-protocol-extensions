import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root = new URL('../', import.meta.url);
const names = {
  'capability-manifest.v1.json': 'CapabilityManifest',
  'capability-record.v1.json': 'CapabilityRecord',
  'capability-action.v1.json': 'CapabilityAction',
  'capability-result.v1.json': 'CapabilityResult',
  'recovery-app-reset-prepare.v1.json': 'RecoveryAppResetPrepare',
  'recovery-app-reset-apply.v1.json': 'RecoveryAppResetApply',
  'recovery-app-reset-restore.v1.json': 'RecoveryAppResetRestore',
};

// This deliberately small generator fails on unknown vocabulary. Runtime bounds
// remain in JSON Schema: TypeScript does not enforce lengths, safe integers or CAS.
const vocabulary = new Set(['$schema','$id','description','type','properties','required',
  'additionalProperties','items','const','enum','minimum','maximum','minLength',
  'maxLength','maxProperties','minItems','maxItems','uniqueItems','pattern','default']);
function type(schema) {
  for (const key of Object.keys(schema)) if (!vocabulary.has(key)) throw Error('Unsupported schema keyword: '+key);
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(v=>JSON.stringify(v)).join(' | ');
  if (schema.type === 'string') return 'string';
  if (['number','integer'].includes(schema.type)) return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'array') return `Array<${type(schema.items)}>`;
  if (schema.type === 'object') {
    const properties = Object.entries(schema.properties??{}).map(([key,value])=>
      `${JSON.stringify(key)}${schema.required?.includes(key)?'':'?'}: ${type(value)};`);
    if (schema.additionalProperties !== false) {
      const additional = schema.additionalProperties;
      properties.push(`[key: string]: ${additional && typeof additional === 'object' ? type(additional) : 'unknown'};`);
    }
    return properties.length ? `{ ${properties.join(' ')} }` : 'Record<string, unknown>';
  }
  if (!Object.keys(schema).length) return 'unknown';
  throw Error('Unsupported schema type: '+schema.type);
}

export function generate() {
  let result = '/** Generated by scripts/generate-types.mjs. Do not edit. Upstream SDKs own AHP/ACP. */\n';
  const files = readdirSync(new URL('schemas/',root)).filter(n=>n.endsWith('.json')).sort();
  for (const filename of files) {
    const name = names[filename];
    if (!name) throw Error('Missing public type name for '+filename);
    const bytes = readFileSync(new URL('schemas/'+filename,root));
    const schema = JSON.parse(bytes);
    let body = type(schema);
    let parameters = '';
    // Preserve the existing public generic API; these substitutions are named
    // adapters over schema fields, not a second handwritten declaration source.
    if (name === 'CapabilityRecord') {
      parameters = '<T extends object = Record<string, unknown>>';
      body = body.replace(`"data": ${type(schema.properties.data)}`, '"data": T');
    }
    if (name === 'CapabilityResult') {
      parameters = '<T = unknown>';
      body = body.replace('"result"?: unknown','"result"?: T');
      body = body.replace(/"updates"\?: Array<.*?>; "invalidate"/, '"updates"?: CapabilityRecord[]; "invalidate"');
    }
    result += `\n/** ${filename}; SHA256 ${createHash('sha256').update(bytes).digest('hex')} */\n`;
    result += `export interface ${name}${parameters} ${body}\n`;
  }
  return result;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = new URL('types/index.d.ts',root), value = generate();
  if (process.argv.includes('--check')) {
    if (readFileSync(output,'utf8') !== value) throw Error('Generated bindings drift; run npm run generate');
  } else writeFileSync(output,value);
}
